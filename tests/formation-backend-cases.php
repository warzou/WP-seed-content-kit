<?php

function wpsck_formation_backend_cases()
{
    $checks = array();
    $ids = array();
    $check = function ($name, $value) use (&$checks) { $checks[$name] = (bool) $value; };
    $create = function ($type, $title, $order = 0) use (&$ids) {
        $id = wp_insert_post(array('post_type' => $type, 'post_status' => 'publish', 'post_title' => 'WPSCK TEMP V4 ' . $title, 'menu_order' => $order), true);
        if (is_wp_error($id)) throw new RuntimeException($id->get_error_message());
        $ids[] = $id;
        return $id;
    };
    $a = $create('seed_program', 'Program A');
    $b = $create('seed_program', 'Program B');
    $s1 = $create('seed_section', 'Stages residentiels', 10);
    $s2 = $create('seed_section', 'Autre niveau futur', 20);
    $s3 = $create('seed_section', 'Program B section', 10);
    foreach (array($s1 => $a, $s2 => $a, $s3 => $b) as $section => $program) update_post_meta($section, '_seed_formation_program_id', $program);
    $t1 = $create('seed_theme', 'Theme A');
    $t2 = $create('seed_theme', 'Theme B');
    $t3 = $create('seed_theme', 'Theme C');
    $v = array('program_id' => $a, 'theme_id' => $t1, 'section_id' => $s1, 'calendar_year' => 2027, 'start_date' => '2027-02-05', 'end_date' => '2027-02-05', 'status' => 'planned', 'annual_display_title' => '', 'person_ids' => array(), 'menu_order' => 0);
    $save = function ($values, $id = 0) use (&$ids) {
        $result = wp_seed_content_formation_store_schedule($values, $id);
        if (is_wp_error($result)) throw new RuntimeException($result->get_error_code() . ': ' . $result->get_error_message());
        if (!$id) $ids[] = $result;
        return $result;
    };
    $n = $save($v);
    $d = wp_seed_content_formation_get_schedule_data($n);
    $check('schedule_create_publish', get_post_status($n) === 'publish');
    $check('single_day_and_zero_people', $d['start_date'] === $d['end_date'] && $d['person_ids'] === array());
    $check('first_publication_order_snapshot', metadata_exists('post', $n, '_seed_formation_section_order_snapshot') && $d['section_order'] === 10);
    $check('annual_title_empty_fallback', $d['display_title'] === get_the_title($t1));
    $duplicate = wp_seed_content_formation_store_schedule($v);
    $check('exact_dated_schedule_duplicate_rejected', is_wp_error($duplicate));
    $bad = $v; $bad['section_id'] = $s3;
    $check('cross_program_section_rejected', in_array('section_program_mismatch', wp_seed_content_formation_validate_schedule_values($bad, $n), true));
    $bad = $v; $bad['end_date'] = '2027-02-04';
    $check('reversed_dates_rejected', is_wp_error(wp_seed_content_formation_store_schedule($bad, $n)));
    $bad = $v; $bad['start_date'] = '2027-02-30';
    $check('impossible_date_rejected', is_wp_error(wp_seed_content_formation_store_schedule($bad, $n)));
    $bad = $v; $bad['calendar_year'] = 2028;
    $check('year_mismatch_rejected', is_wp_error(wp_seed_content_formation_store_schedule($bad, $n)));
    $bad = $v; $bad['status'] = 'unknown';
    $check('unknown_status_rejected', is_wp_error(wp_seed_content_formation_store_schedule($bad, $n)));
    $bad = $v; $bad['person_ids'] = array($a);
    $check('wrong_person_type_rejected', is_wp_error(wp_seed_content_formation_store_schedule($bad, $n)));
    $v['annual_display_title'] = 'Annual title 2027'; $v['end_date'] = '2027-02-07';
    $save($v, $n);
    $d = wp_seed_content_formation_get_schedule_data($n);
    $check('update_multiday_annual_title', $d['end_date'] === '2027-02-07' && $d['display_title'] === 'Annual title 2027');
    $people = get_posts(array('post_type' => 'seed_directory', 'post_status' => 'publish', 'posts_per_page' => 2, 'fields' => 'ids'));
    if (count($people) >= 2) {
        $v['person_ids'] = array_reverse(array_map('intval', $people));
        $save($v, $n);
        $save($v, $n);
        $check('ordered_people_roundtrip', get_post_meta($n, '_seed_formation_directory_person_ids', true) === $v['person_ids']);
        $v['person_ids'] = array($v['person_ids'][0]); $save($v, $n);
        $check('single_person_roundtrip', count(get_post_meta($n, '_seed_formation_directory_person_ids', true)) === 1);
    }
    $v['status'] = 'postponed'; $v['start_date'] = '2027-03-05'; $v['end_date'] = '2027-03-07'; $save($v, $n);
    $d = wp_seed_content_formation_get_schedule_data($n);
    $check('first_postponement_original_pair', $d['original_start_date'] === '2027-02-05' && $d['original_end_date'] === '2027-02-07');
    $v['start_date'] = '2027-04-05'; $v['end_date'] = '2027-04-07'; $save($v, $n);
    $d = wp_seed_content_formation_get_schedule_data($n);
    $check('second_postponement_preserves_pair', $d['original_start_date'] === '2027-02-05' && $d['original_end_date'] === '2027-02-07');
    $history = $d;
    wp_update_post(array('ID' => $t1, 'post_title' => 'WPSCK TEMP V4 Renamed theme', 'post_excerpt' => 'Summary', 'post_content' => '<p>Description</p>'));
    wp_update_post(array('ID' => $s1, 'post_title' => 'WPSCK TEMP V4 Renamed section', 'menu_order' => 90));
    wp_update_post(array('ID' => $a, 'post_title' => 'WPSCK TEMP V4 Renamed program', 'post_content' => '<p>Program content</p>', 'post_status' => 'draft'));
    $check('program_edit_draft', get_post($a)->post_content === '<p>Program content</p>' && get_post_status($a) === 'draft');
    wp_update_post(array('ID' => $a, 'post_status' => 'publish'));
    $check('theme_summary_content', get_post($t1)->post_excerpt === 'Summary' && get_post($t1)->post_content === '<p>Description</p>');
    $d = wp_seed_content_formation_get_schedule_data($n);
    $check('canonical_rename_keeps_schedule_history', $d['theme_title_snapshot'] === $history['theme_title_snapshot'] && $d['section_label'] === $history['section_label'] && $d['section_order'] === 10);
    $next = $v; $next['calendar_year'] = 2028; $next['start_date'] = '2028-05-01'; $next['end_date'] = '2028-05-03'; $next['status'] = 'planned'; $next['annual_display_title'] = 'Annual title 2028';
    $n2 = $save($next);
    $check('same_theme_reused_next_year', wp_seed_content_formation_get_schedule_data($n2)['calendar_year'] === 2028);
    $check('next_year_uses_current_snapshots', wp_seed_content_formation_get_schedule_data($n2)['section_order'] === 90);
    $check('2027_unchanged_after_2028', wp_seed_content_formation_get_schedule_data($n) === $d);
    $other = $next; $other['program_id'] = $b; $other['section_id'] = $s3; $other['calendar_year'] = 2027; $other['start_date'] = '2027-01-01'; $other['end_date'] = '2027-01-02';
    $nb = $save($other);
    $check('same_theme_reused_other_program', !is_wp_error($nb));
    $check('program_filter_isolation', array_column(wp_seed_content_formation_get_schedules(array('program_id' => $b)), 'id') === array($nb));
    $check('year_filter_isolation', array_column(wp_seed_content_formation_get_schedules(array('program_id' => $a, 'year' => 2028)), 'id') === array($n2));
    $check('empty_calendar', wp_seed_content_formation_get_schedules(array('program_id' => $b, 'year' => 2028)) === array());
    $check('program_years_isolated', wp_seed_content_formation_get_program_calendar_years($b) === array(2027));
    $v['theme_id'] = $t2; $v['section_id'] = $s2; $v['annual_display_title'] = ''; $save($v, $n);
    $d = wp_seed_content_formation_get_schedule_data($n);
    $check('explicit_relation_edit_refreshes_only_current_snapshot', $d['theme_title_snapshot'] === get_the_title($t2) && $d['section_label'] === get_the_title($s2) && $d['section_order'] === 20 && wp_seed_content_formation_get_schedule_data($n2)['section_order'] === 90);
    $check('referenced_program_trash_blocked', false === wp_trash_post($a));
    $check('referenced_theme_delete_blocked', false === wp_delete_post($t2, true));
    $check('referenced_section_delete_blocked', false === wp_delete_post($s2, true));
    $free = $create('seed_section', 'Empty section');
    update_post_meta($free, '_seed_formation_program_id', $b);
    $check('unused_section_trash_allowed', (bool) wp_trash_post($free));
    $check('unused_section_permanent_delete_allowed', (bool) wp_delete_post($free, true));
    $v['status'] = 'cancelled'; $save($v, $n);
    $check('cancelled_remains_stored', get_post_meta($n, '_seed_formation_status', true) === 'cancelled');
    $check('cancelled_excluded_chronological', wp_seed_content_formation_get_schedules(array('program_id' => $a, 'year' => 2027)) === array());
    $check('cancelled_excluded_grouped', wp_seed_content_formation_get_grouped_calendar(array('program_id' => $a, 'year' => 2027)) === array());
    $check('cancelled_in_structure', count(wp_seed_content_formation_get_structure(array('program_id' => $a, 'year' => 2027))) === 1);
    $check('cancelled_excluded_next', wp_seed_content_formation_get_next_schedule($s2, array('today' => '2027-01-01')) === array());
    $v['status'] = 'planned'; $save($v, $n);
    $v3 = $v; $v3['theme_id'] = $t3; $v3['start_date'] = '2027-01-02'; $v3['end_date'] = '2027-01-03'; $v3['menu_order'] = 50; $n3 = $save($v3);
    $check('chronological_dates_first', array_column(wp_seed_content_formation_get_schedules(array('program_id' => $a, 'year' => 2027)), 'id') === array($n3, $n));
    $group = wp_seed_content_formation_get_grouped_calendar(array('program_id' => $a, 'year' => 2027));
    $check('grouped_manual_order_first', array_column($group[0]['items'], 'id') === array($n, $n3));
    foreach (array('structure', 'grouped', 'calendar') as $mode) {
        $html = wp_seed_content_formation_shortcode(array('program' => $b, 'year' => 2027, 'mode' => $mode));
        $check('shortcode_' . $mode . '_isolated', strpos($html, get_the_title($s2)) === false && strpos($html, get_the_title($s3)) !== false);
    }
    $check('schedule_trash_allowed', (bool) wp_trash_post($n3));
    $check('trashed_relation_still_protected', false === wp_delete_post($t3, true));
    $check('schedule_permanent_delete_allowed', (bool) wp_delete_post($n3, true));
    $check('deleted_schedule_absent', !get_post($n3));
    $check('deleted_schedule_not_projected', !in_array($n3, array_column(wp_seed_content_formation_get_schedules(array('program_id' => $a, 'year' => 2027)), 'id'), true));
    $check('unreferenced_theme_delete_allowed', (bool) wp_delete_post($t3, true));
    $c = $create('seed_program', 'Multiplicity');
    $cs = $create('seed_section', 'Repeated sessions', 10);
    $cs2 = $create('seed_section', 'Another section', 20);
    foreach (array($cs, $cs2) as $section) update_post_meta($section, '_seed_formation_program_id', $c);
    $ct = $create('seed_theme', 'Generic repeated theme');
    $base = array('program_id'=>$c, 'theme_id'=>$ct, 'section_id'=>$cs, 'calendar_year'=>2026, 'start_date'=>'2026-01-15', 'end_date'=>'2026-01-15', 'status'=>'planned', 'annual_display_title'=>'', 'person_ids'=>array(), 'menu_order'=>0);
    $seven = array();
    foreach (array('01-15','02-26','04-09','05-21','07-02','10-15','12-03') as $day) {
        $row = $base; $row['start_date'] = $row['end_date'] = '2026-' . $day;
        $seven[] = $save($row);
    }
    $scope = array('program_id'=>$c,'year'=>2026);
    $check('multiplicity_seven_created', count($seven) === 7);
    $check('multiplicity_chrono_all', array_column(wp_seed_content_formation_get_schedules($scope),'id') === $seven);
    $group = wp_seed_content_formation_get_grouped_calendar($scope);
    $check('multiplicity_grouped_all', array_column($group[0]['items'],'id') === $seven);
    $structure = wp_seed_content_formation_get_structure($scope);
    $check('multiplicity_structure_once', count($structure[0]['items']) === 1);
    $check('multiplicity_structure_schedule_id_preserved', $structure[0]['items'][0]['id'] === $seven[0] && $structure[0]['items'][0]['theme_id'] === $ct);
    $check('multiplicity_exact_rejected', is_wp_error(wp_seed_content_formation_store_schedule($base)));
    $check('multiplicity_self_update', $save($base, $seven[0]) === $seven[0]);
    $peer = wp_seed_content_formation_get_schedule_data($seven[1]);
    $collision = $base; $collision['start_date'] = $collision['end_date'] = '2026-02-26';
    $check('multiplicity_update_collision_rejected', is_wp_error(wp_seed_content_formation_store_schedule($collision, $seven[0])));
    $check('multiplicity_collision_no_write', wp_seed_content_formation_get_schedule_data($seven[0])['start_date'] === '2026-01-15');
    $check('multiplicity_next_skips_past', wp_seed_content_formation_get_next_schedule($cs, array_merge($scope,array('today'=>'2026-02-01')))['id'] === $seven[1]);
    $cancel = $collision; $cancel['status'] = 'cancelled'; $save($cancel, $seven[1]);
    $check('multiplicity_cancelled_skipped', wp_seed_content_formation_get_next_schedule($cs, array_merge($scope,array('today'=>'2026-02-01')))['id'] === $seven[2]);
    $check('multiplicity_cancelled_duplicate_reserved', is_wp_error(wp_seed_content_formation_store_schedule($collision)));
    $unchanged = wp_seed_content_formation_get_schedule_data($seven[1]);
    $move = $base; $move['status'] = 'postponed'; $move['start_date'] = $move['end_date'] = '2026-03-01'; $save($move, $seven[0]);
    $check('multiplicity_update_free_date', wp_seed_content_formation_get_schedule_data($seven[0])['start_date'] === '2026-03-01');
    $check('multiplicity_postponed_originals', wp_seed_content_formation_get_schedule_data($seven[0])['original_start_date'] === '2026-01-15');
    $check('multiplicity_postponed_peer_unchanged', wp_seed_content_formation_get_schedule_data($seven[1]) === $unchanged);
    $check('multiplicity_postponed_next', wp_seed_content_formation_get_next_schedule($cs,array_merge($scope,array('today'=>'2026-02-01')))['id'] === $seven[0]);
    $move['start_date'] = $move['end_date'] = '2026-03-02'; $save($move, $seven[0]);
    $check('multiplicity_originals_immutable', wp_seed_content_formation_get_schedule_data($seven[0])['original_end_date'] === '2026-01-15');
    $structure = wp_seed_content_formation_get_structure($scope);
    $check('multiplicity_structure_representative_stable_after_report', $structure[0]['items'][0]['id'] === $seven[0]);
    $different = $base; $different['section_id'] = $cs2; $different['start_date'] = $different['end_date'] = '2026-02-26';
    $section_copy = $save($different);
    $check('multiplicity_same_dates_other_section', $section_copy > 0);
    $structure = wp_seed_content_formation_get_structure($scope);
    $check('multiplicity_structure_per_section', count($structure) === 2 && count($structure[0]['items']) === 1 && count($structure[1]['items']) === 1);
    $different['program_id'] = $b; $different['section_id'] = $s3;
    $check('multiplicity_same_dates_other_program', $save($different) > 0);
    $two = array();
    foreach (array('2027-12-17','2027-12-19') as $day) {
        $row = $base; $row['calendar_year'] = 2027; $row['start_date'] = $row['end_date'] = $day; $row['annual_display_title'] = 'Two separate days';
        $two[] = $save($row);
    }
    $scope27 = array('program_id'=>$c,'year'=>2027);
    $check('multiplicity_year_isolation', array_column(wp_seed_content_formation_get_schedules($scope27),'id') === $two);
    $check('multiplicity_2026_preserved', count(wp_seed_content_formation_get_schedules(array_merge($scope,array('include_cancelled'=>true)))) === 8);
    $check('multiplicity_discontinuous_dates', array_column(wp_seed_content_formation_get_schedules($scope27),'end_date') === array('2027-12-17','2027-12-19'));
    $check('multiplicity_discontinuous_next', wp_seed_content_formation_get_next_schedule($cs,array_merge($scope27,array('today'=>'2027-12-18')))['id'] === $two[1]);
    $html = wp_seed_content_formation_shortcode(array('program'=>$c,'year'=>2027,'mode'=>'calendar'));
    $check('multiplicity_discontinuous_html', substr_count($html,'<time ') === 2 && strpos($html,'datetime="2027-12-18"') === false);
    $structure = wp_seed_content_formation_get_structure(array('program_id'=>$c));
    $check('multiplicity_structure_years_not_merged', count($structure[0]['items']) === 2);
    $check('multiplicity_delete_one_only', (bool) wp_delete_post($two[0],true) && (bool) get_post($two[1]));
    return array('checks' => $checks, 'fixture_ids' => $ids);
}
